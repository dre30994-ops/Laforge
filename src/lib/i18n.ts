export function chainCopy(
  t: (path: string, vars?: Record<string, string | number>) => string,
  key: string,
  kind: "label" | "short" = "label",
  fallback = key,
): string {
  const path = kind === "short" ? `chain.${key}Short` : `chain.${key}`;
  const value = t(path);
  return value === path ? fallback : value;
}
